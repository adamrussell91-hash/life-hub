#!/usr/bin/env node
/**
 * Capacity weather icons: Adam's 30 supplied SVGs, recoloured by condition family.
 *
 *   in:  packages/design-kit/icons/capacity-weather/src/N.svg   (Adam's originals, never edited)
 *   out: packages/design-kit/icons/capacity-weather/N.svg       (condition-coloured, standalone)
 *        packages/design-kit/js/calendar/weather-icons.js        (same SVGs as strings, for inline use)
 *
 * Shapes and numbering are untouched. Only colours change: every original colour has a
 * role (outline, sun, cloud, accent line, bolt, moon) and each condition family paints
 * those roles in its own hue, so sunny reads warm, fog reads lavender, rain reads blue.
 * Run after changing a palette: `node scripts/build-weather-icons.mjs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'packages/design-kit/icons/capacity-weather/src');
const OUT = join(ROOT, 'packages/design-kit/icons/capacity-weather');
const MODULE = join(ROOT, 'packages/design-kit/js/calendar/weather-icons.js');

/** Original colour → role. Anything else fails the build (a new colour needs a role). */
const ROLE = {
  '#344D61': 'ink',
  '#F1BC55': 'sun',
  '#FFF3CD': 'sunHi',
  '#438F98': 'accent',
  '#D1DDE3': 'cloud',
  '#9EAFC0': 'cloudDark',
  '#CFB7DE': 'bolt',
  '#817595': 'boltInk',
  '#A6B9D9': 'moon'
};

/** Condition families (weather-states.md rendering rules) and their role colours. */
export const FAMILIES = {
  clear: { ink: '#7A4A12', sun: '#F5A524', sunHi: '#FFE7A3', accent: '#E07A1F', cloud: '#FCE8C8', cloudDark: '#F2C98C', bolt: '#FFD23F', boltInk: '#8A5A00', moon: '#F5D27A' },
  steady: { ink: '#2F5D3E', sun: '#F2C14E', sunHi: '#FFF1C2', accent: '#3F9460', cloud: '#DCEFD9', cloudDark: '#A9D3B0', bolt: '#FFD23F', boltInk: '#8A5A00', moon: '#CDE8D2' },
  wind: { ink: '#145A63', sun: '#F2C14E', sunHi: '#FFF1C2', accent: '#1C97A6', cloud: '#D3EEF1', cloudDark: '#92CFD6', bolt: '#FFD23F', boltInk: '#8A5A00', moon: '#BFE6EA' },
  cloud: { ink: '#3A4A5C', sun: '#E8C26A', sunHi: '#FFF1C2', accent: '#6E8199', cloud: '#D9E0E8', cloudDark: '#A3B0C0', bolt: '#FFD23F', boltInk: '#8A5A00', moon: '#C8D1DD' },
  fog: { ink: '#4F4868', sun: '#E9C978', sunHi: '#FFF1C2', accent: '#8C83B0', cloud: '#E6E2EF', cloudDark: '#B9B2D1', bolt: '#FFD23F', boltInk: '#8A5A00', moon: '#D9D4EA' },
  rain: { ink: '#1E3F73', sun: '#EDC46A', sunHi: '#FFF1C2', accent: '#3B7DD8', cloud: '#D6E3F5', cloudDark: '#93AEDB', bolt: '#FFD23F', boltInk: '#8A5A00', moon: '#C4D5F0' },
  storm: { ink: '#34264F', sun: '#F0C35C', sunHi: '#FFF1C2', accent: '#5B6FC4', cloud: '#D2C9E4', cloudDark: '#8D7FB6', bolt: '#FFD23F', boltInk: '#8A5A00', moon: '#CFC6E6' },
  recovery: { ink: '#22584A', sun: '#F4B942', sunHi: '#FFEFC0', accent: '#2E9C7A', cloud: '#D6EFE6', cloudDark: '#9ED2BF', bolt: '#F7D46A', boltInk: '#8A6A10', moon: '#C9EADF' },
  evening: { ink: '#2B2F5E', sun: '#F5D27A', sunHi: '#FFF1C2', accent: '#5A63B5', cloud: '#D9DCF2', cloudDark: '#A8AEDF', bolt: '#FFD23F', boltInk: '#8A5A00', moon: '#C9CEF2' }
};

/** Icon number → family. Mirrors WEATHER_STATES in readiness-model.js (tested). */
export const ICON_FAMILY = {
  1: 'clear', 2: 'clear', 3: 'clear', 4: 'clear', 5: 'clear', 6: 'clear', 7: 'clear',
  8: 'steady', 9: 'steady',
  10: 'wind', 11: 'wind', 12: 'wind',
  13: 'cloud', 14: 'cloud', 15: 'cloud', 16: 'cloud', 17: 'cloud',
  18: 'fog', 19: 'fog', 20: 'fog', 21: 'fog',
  22: 'rain', 23: 'rain', 24: 'rain', 25: 'rain',
  26: 'storm', 27: 'storm',
  28: 'recovery', 29: 'recovery',
  30: 'evening'
};

export function recolour(svg, family) {
  const palette = FAMILIES[family];
  if (!palette) throw new Error(`Unknown family ${family}`);
  return svg.replace(/#[0-9A-Fa-f]{6}\b/g, hex => {
    const role = ROLE[hex.toUpperCase()];
    if (!role) throw new Error(`Colour ${hex} has no role; add it to ROLE`);
    return palette[role];
  });
}

function build() {
  const icons = {};
  for (let n = 1; n <= 30; n += 1) {
    const original = readFileSync(join(SRC, `${n}.svg`), 'utf8').trim();
    const family = ICON_FAMILY[n];
    const coloured = recolour(original, family)
      // Unique title ids so 30 inline icons on one page stay valid.
      .replace('aria-labelledby="title"', `aria-labelledby="wx-title-${n}"`)
      .replace('<title id="title">', `<title id="wx-title-${n}">`);
    writeFileSync(join(OUT, `${n}.svg`), `${coloured}\n`);
    icons[n] = coloured;
  }
  const body = Object.entries(icons).map(([n, svg]) => `  ${n}: ${JSON.stringify(svg)}`).join(',\n');
  writeFileSync(MODULE, `/**
 * GENERATED by scripts/build-weather-icons.mjs — do not edit by hand.
 * Adam's 30 capacity weather icons (shapes untouched), recoloured by condition family.
 */
export const WEATHER_ICON_FAMILY = Object.freeze(${JSON.stringify(ICON_FAMILY)});

export const WEATHER_ICONS = Object.freeze({
${body}
});

/** Inline SVG for a state number (1–30); '' for anything else. */
export function weatherIconSvg(n) {
  return WEATHER_ICONS[n] ?? '';
}
`);
  return Object.keys(icons).length;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  console.log(`weather icons: ${build()} written`);
}
