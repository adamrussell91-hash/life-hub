export function fragrancePhotoUrl(name) {
  const photo = Object.hasOwn(FRAGRANCE_PHOTOS, name) ? FRAGRANCE_PHOTOS[name] : null;
  return photo ? new URL(`../../../assets/fragrances/${photo.file}`, import.meta.url).href : null;
}

/** Decorative next to the fragrance name. Reserve the same frame on missing/failed images. */
export function createFragrancePhoto(doc, name, { width = 72, eager = false } = {}) {
  const frame = doc.createElement('span');
  frame.className = 'aes-photo';
  frame.style.width = `${width}px`;
  frame.setAttribute('aria-hidden', 'true');
  const fallback = () => {
    frame.classList.add('aes-photo--fallback');
    const svg = doc.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('viewBox', '0 0 64 64');
    const path = doc.createElementNS(svg.namespaceURI, 'path');
    path.setAttribute('d', 'M25 8h14v10H25z M27 18h10v6H27z M22 24h20q6 0 6 6v22q0 4-4 4H20q-4 0-4-4V30q0-6 6-6z M24 36h16v10H24z');
    svg.append(path);
    frame.replaceChildren(svg);
    frame.title = `Photo unavailable for ${name}`;
  };
  const src = fragrancePhotoUrl(name);
  if (!src) { fallback(); return frame; }
  const img = doc.createElement('img');
  img.alt = '';
  img.width = 512;
  img.height = 512;
  img.loading = eager ? 'eager' : 'lazy';
  img.decoding = 'async';
  img.addEventListener('error', fallback, { once: true });
  img.src = src;
  frame.append(img);
  return frame;
}
