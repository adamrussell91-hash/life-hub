// never return them, so the guide can only name one as a caution, never offer it as a detour.
//
// Snare: { id: 'sn_<name>', title, when, check, signals, counters, tells }
//   when:     what it looks like from the inside, one line, second person
//   check:    the one question to ask yourself, one line
//   signals:  from SIGNALS; at least one
//   counters: 1–3 map option ids that help; every one must exist (mapProblems checks)
//   tells:    keyword RegExp (case-insensitive) used on situation, digest and step text
