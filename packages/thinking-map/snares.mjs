const BY_ID = new Map(SNARES.map((snare) => [snare.id, snare]));

/** One snare by id, or null. */
export const getSnare = (id) => BY_ID.get(id) ?? null;

/**
 * Snares worth watching for, ranked: a tells match scores 3 and each shared signal 1; ties keep
 * list order; a score of 0 is dropped.
 */
export function snaresFor({ signals = [], text = '', limit = 6 } = {}) {
  const wanted = new Set((signals ?? []).filter((sig) => SIGNAL_IDS.includes(sig)));
  const clean = String(text ?? '');
  return SNARES
    .map((snare, order) => {
      const told = clean.trim() && snare.tells.test(clean) ? 3 : 0;
      return { snare, order, score: told + snare.signals.filter((sig) => wanted.has(sig)).length };
    })
    .filter((row) => row.score > 0)
    .sort((a, b) => b.score - a.score || a.order - b.order)
    .slice(0, Math.max(0, limit))
    .map((row) => row.snare);
}
