// Rebuilds ../day-dial.html from this folder. Run from the repo root:
//   node docs/proposals/calendar-reference/day-dial/src/build-ref.mjs
// Needs root node_modules (esbuild). Bundles the REAL modules: lead-lines.js, openings.js, almanac-rules.js, capacity-model.js,
// ghost-writes.js, hub-motion.js (pill thumb) and apps/tasks/src/views/timeline-motion.ts.
import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.resolve(here, '..');
const res = await build({
  entryPoints: [path.join(here, 'dial-ref.ts')],
  bundle: true, write: false, format: 'iife', target: 'es2022', platform: 'browser', legalComments: 'none'
});
const js = res.outputFiles[0].text.replace(/<\/script>/g, '<\\/script>');
const tpl = fs.readFileSync(path.join(here, 'dial.template.html'), 'utf8');
const banner = '/* Generated from src/dial-ref.ts. Do not edit day-dial.html; edit src/ and rebuild. */\n';
fs.writeFileSync(path.join(out, 'day-dial.html'), tpl.replace('/*__BUNDLE__*/', () => banner + js));
// Data: the Tideline fixture (../../fixture.json is generated by the Tideline build).
console.log('built day-dial.html', (js.length / 1024).toFixed(1) + 'KB', '');
