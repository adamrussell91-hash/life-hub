test('dial phase 3: the day is revealed clockwise from noon, and the hand swings to now', async () => {
  const { context, page } = await open({ settle: 0 });
  try {
    const frames = await page.evaluate(async () => {
      const out = [];
      const t0 = performance.now();
      while (performance.now() - t0 < 1500) {
        await new Promise(r => requestAnimationFrame(r));
        const gastro = document.querySelector('[data-id="gastro"].dd-arc')?.getAttribute('d') ?? '';
        const morning = document.querySelector('[data-part="context-ring"] .dd-ctx--school')?.getAttribute('d') ?? '';
        const sleep = document.querySelector('[data-part="context-ring"] .dd-ctx--sleep')?.getAttribute('d') ?? '';
        out.push({ gastro: gastro.length, morning: morning.length, sleepD: sleep });
      }
      return out;
    });
    const firstGastro = frames.findIndex(f => f.gastro > 0);
    const firstMorning = frames.findIndex(f => f.morning > 0);
    assert.ok(firstGastro >= 0 && firstMorning > firstGastro, 'the 1:15 pm arc appears before the morning (clockwise from noon)');
    assert.ok(new Set(frames.map(f => f.sleepD)).size >= 5, 'the 8-hour sleep wall grows over frames, not all at once');
  } finally { await context.close(); }
});

test('dial phase 3: reduced motion lands at once; resizing re-lays out without replaying', async () => {
  const { context, page } = await open({ reducedMotion: 'reduce', settle: 0 });
  try {
    await page.evaluate(() => new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r))));
    assert.ok((await page.locator('[data-part="context-ring"] .dd-ctx--school').getAttribute('d')).length > 0, 'the whole day is drawn immediately');
  } finally { await context.close(); }
  const second = await open();
  try {
    const { page } = second;
    const w1 = await page.locator('[data-part="dial"]').evaluate(s => +s.getAttribute('width'));
    await page.setViewportSize({ width: 1180, height: 1350 });
    const frames = await page.evaluate(async () => {
      const out = [];
      const t0 = performance.now();
      while (performance.now() - t0 < 700) { await new Promise(r => requestAnimationFrame(r)); out.push(document.querySelector('[data-part="context-ring"] .dd-ctx--school')?.getAttribute('d')?.length ?? 0); }
      return out;
    });
    const w2 = await page.locator('[data-part="dial"]').evaluate(s => +s.getAttribute('width'));
    assert.ok(w2 <= w1, 'the dial re-lays out for the narrower column');
    assert.ok(frames.every(n => n > 0), 'resizing never replays the entrance');
  } finally { await second.context.close(); }
});

