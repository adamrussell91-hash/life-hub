test('dial phase 2: noon is up, time runs clockwise, and each arc sits at its time', async () => {
  const { context, page } = await open();
  try {
    const c = await centre(page);
    const near = (a, b, tol) => { const d = Math.abs(a - b); return Math.min(d, 2 * Math.PI - d) <= tol; };
    const gastro = await boxOf(page, '[data-id="gastro"].dd-arc');
    assert.ok(near(angleFromTop(c, gastro), angleForHour(13.75), 0.25), 'the 1:15 pm appointment is just right of noon');
    const corey = await boxOf(page, '[data-id="thu-corey"].dd-arc');
    assert.ok(near(angleFromTop(c, corey), angleForHour(20.5), 0.25), 'Corey’s evening is on the lower right');
    const hand = await page.locator('[data-part="now-hand"]').evaluate(n => ({ x: +n.getAttribute('x2'), y: +n.getAttribute('y2') }));
    const svgBox = await page.locator('[data-part="dial"]').evaluate(s => { const r = s.getBoundingClientRect(); return { left: r.left, top: r.top }; });
    assert.ok(near(angleFromTop(c, { x: svgBox.left + hand.x, y: svgBox.top + hand.y }), angleForHour(NOW_H), 0.03), 'the hand points at 6:05 pm');
    const sleep = await page.locator('.dd-ctx--sleep').first().evaluate(n => { const b = n.getBBox(); return { x: b.x + b.width / 2, y: b.y + b.height / 2 }; });
    const height = await page.locator('[data-part="dial"]').evaluate(s => +s.getAttribute('height'));
    assert.ok(sleep.y > height / 2, 'the sleep wall is in the bottom half');
  } finally { await context.close(); }
});

test('dial phase 2: laid out at its real width; labels never collide or leave the dial', async () => {
  for (const width of [960, 1280, 1600]) {
    const { context, page } = await open({ width });
    try {
      const r = await page.evaluate(() => {
        const svg = document.querySelector('[data-part="dial"]');
        const box = svg.getBoundingClientRect();
        const texts = [...svg.querySelectorAll('text')].filter(t => t.textContent.trim()).map(t => ({ t: t.textContent, b: t.getBoundingClientRect() }));
        const clashes = [];
        for (let i = 0; i < texts.length; i++) for (let j = i + 1; j < texts.length; j++) {
          const a = texts[i].b, c = texts[j].b;
          if (Math.min(a.right, c.right) - Math.max(a.left, c.left) > 2 && Math.min(a.bottom, c.bottom) - Math.max(a.top, c.top) > 2) clashes.push(`${texts[i].t} × ${texts[j].t}`);
        }
        const outside = texts.filter(x => x.b.right > box.right + 0.5 || x.b.left < box.left - 0.5 || x.b.top < box.top - 0.5 || x.b.bottom > box.bottom + 0.5).map(x => x.t);
        return { attr: +svg.getAttribute('width'), css: box.width, clashes, outside, scroll: document.documentElement.scrollWidth, inner: innerWidth };
      });
      assert.ok(Math.abs(r.attr - r.css) < 1, `at ${width}px the dial is scaled (${r.attr} drawn, ${r.css} shown)`);
      assert.deepEqual(r.clashes, [], `labels collide at ${width}px`);
      assert.deepEqual(r.outside, [], `labels leave the dial at ${width}px`);
      assert.ok(r.scroll <= r.inner, `the page scrolls sideways at ${width}px`);
      if (width === 960) await shot(page, 'dial-960');
    } finally { await context.close(); }
  }
});

