const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = process.env.DIAL_REPO_ROOT ?? path.resolve(HERE, HERE.includes('docs/proposals') ? '../../../..' : '../..');
const APP = process.env.DIAL_APP === '1';
