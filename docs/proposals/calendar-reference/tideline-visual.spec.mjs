test('phase 4: a proposal previews exactly what Accept writes, then writes it', async () => {
  const { context, page } = await open();
  try {
    const posts = [];
    if (APP) page.on('request', r => { if (r.url().includes('/api/calendar-ghosts')) posts.push(r.postDataJSON()); });
    const workout = page.locator('[data-id="thu-workout"]');
    assert.match(await workout.getAttribute('class'), /has-proposal/);
    assert.match(await workout.locator('[data-part="proposal"]').textContent(), /Sara suggests: skip workout/);
    await workout.click();
    const pop = page.locator('[data-part="chip-popover"]');
    await pop.waitFor({ state: 'visible' });
    assert.ok((await pop.locator('[data-part="write-preview"]').textContent()).includes(SKIP_LINE));
    await shot(page, 'popover-1280');
    await pop.getByRole('button', { name: 'Accept' }).click();
    await page.waitForTimeout(800);
    assert.ok((await page.locator('[data-part="toast"]').textContent()).includes(SKIP_LINE));
    assert.match(await workout.getAttribute('class'), /is-skipped/);
    assert.doesNotMatch(await workout.getAttribute('class'), /has-proposal/);
    assert.equal(await workout.locator('.cal-chip__meta').textContent(), 'Skipped · Sara');
    if (APP) assert.deepEqual(posts, [{ id: 'g-skip', decision: 'accept' }]);
  } finally {
    await context.close();
  }
});

