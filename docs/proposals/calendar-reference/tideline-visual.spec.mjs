    assert.equal(await page.locator('[data-part="day-head"]').count(), 7);
    assert.match(await page.locator('[data-part="day-head"][data-date="2026-09-24"]').getAttribute('class'), /is-today/);
    const pct = await page.locator('[data-part="capacity"]').evaluateAll(n => n.map(x => Number(x.dataset.pct)));
