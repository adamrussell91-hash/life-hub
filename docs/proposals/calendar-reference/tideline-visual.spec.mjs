const SKIP_LINE = 'Sara→Chadwick: skip Thu 24/09 workout (capacity 34%, sore throat).';

let browser;
let server;
let appUrl;

before(async () => {
  browser = await chromium.launch({ headless: true });
  if (APP) {
    await import(pathToFileURL(path.join(REPO, 'scripts/prepare-web.mjs')).href);
    const { createStaticServer } = await import(pathToFileURL(path.join(REPO, 'scripts/serve.mjs')).href);
    const { once } = await import('node:events');
    server = createStaticServer({ root: pathToFileURL(path.join(REPO, 'dist/')), apiRoot: pathToFileURL(REPO + '/') });
    server.listen(0, '127.0.0.1');
    await once(server, 'listening');
    appUrl = `http://127.0.0.1:${server.address().port}`;
  }
});
after(async () => {
  await browser?.close();
  server?.close();
});

async function open({ width = 1280, height = 1120, reducedMotion = 'no-preference' } = {}) {
  const context = await browser.newContext({ viewport: { width, height }, deviceScaleFactor: 2, reducedMotion });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  if (APP) {
    await page.clock.setFixedTime(new Date('2026-09-24T18:05:00+10:00'));
    await page.goto(appUrl);
    await page.locator('#sign-in-passphrase').fill('life-hub-local');
    await page.locator('#sign-in-button').click();
    await page.locator('#app[data-state="ready"]').waitFor();
    const seeded = await page.evaluate(async () => (await fetch('/api/calendar-visual-seed', { method: 'POST' })).ok);
    assert.equal(seeded, true, 'calendar-visual-seed failed');
    await page.evaluate(() => { location.hash = '#/calendar'; });
  } else {
    await page.goto(REF_URL);
  }
  await page.locator('[data-part="tideline"]').waitFor();
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(700); // entrance finished
  return { context, page, errors };
}
const bandHeights = page => page.evaluate(() =>
  ['morning', 'school', 'after', 'yours'].map(id => document.querySelector(`[data-part="band-${id}"]`).getBoundingClientRect().height));
const approx = (a, b, tol = 1) => Math.abs(a - b) <= tol;
const shot = (page, name) => page.screenshot({ path: path.join(OUT, `${name}.png`) });

