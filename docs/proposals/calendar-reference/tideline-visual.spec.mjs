const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = process.env.TIDELINE_REPO_ROOT ?? path.resolve(HERE, HERE.includes('docs/proposals') ? '../../..' : '../..');
const APP = process.env.TIDELINE_APP === '1';
