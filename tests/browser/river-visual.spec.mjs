async function goToRiver(page) {
  if (APP) await page.evaluate(() => { location.hash = '#/calendar/term'; });
  await page.locator('[data-part="term-river"]').waitFor();
}
async function open({ width = 1280, height = 1100, reducedMotion = 'no-preference', settle = 1400, seed = true } = {}) {
  const context = await browser.newContext({ viewport: { width, height }, deviceScaleFactor: 2, reducedMotion });
  const page = await context.newPage();
  const errors = [];
  const posts = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (r.method() === 'POST' && r.url().includes('/api/calendar-ghosts')) posts.push(r.postDataJSON()); });
  if (APP) {
    await page.clock.setFixedTime(new Date('2026-09-24T18:05:00+10:00'));
    await page.goto(appUrl);
    await page.locator('#sign-in-passphrase').fill('life-hub-local');
    await page.locator('#sign-in-button').click();
    await page.locator('#app[data-state="ready"]').waitFor();
    if (seed) assert.equal(await page.evaluate(async () => (await fetch('/api/calendar-visual-seed', { method: 'POST' })).ok), true);
  } else {
    await page.goto(REF_URL);
  }
  await goToRiver(page);
  await page.evaluate(() => document.fonts.ready);
  if (settle) await page.waitForTimeout(settle);
  return { context, page, errors, posts };
}
const shot = (page, name) => page.screenshot({ path: path.join(OUT, `${name}.png`) });
const frames = (page, ms, probe) => page.evaluate(async ({ ms, probe }) => {
  const f = new Function(`return (${probe})`)();
  const out = [];
  const t0 = performance.now();
  while (performance.now() - t0 < ms) { await new Promise(r => requestAnimationFrame(r)); out.push(f()); }
  return out;
}, { ms, probe: probe.toString() });
const barX = (page, id) => page.evaluate(id => +document.querySelector(`[data-part="term-river"] rect[data-id="${id}"]`)?.getAttribute('x'), id);
const clipW = () => +document.querySelector('#tr-plot rect, clipPath rect')?.getAttribute('width');

/** Visible SVG text: non-empty, not faded out. */
const textAudit = () => {
  const svg = document.querySelector('[data-part="chart"]');
  const box = svg.getBoundingClientRect();
  const { labelW, padR } = window.__termRiver.TR;
  const W = +svg.getAttribute('width');
  const visible = t => t.textContent.trim() && getComputedStyle(t).opacity !== '0' && +(t.getAttribute('opacity') ?? 1) > 0.01;
  const texts = [...svg.querySelectorAll('text')].filter(visible).map(t => ({ t: t.textContent, b: t.getBoundingClientRect(), plot: !!t.closest('[clip-path]') }));
  const clashes = [];
  for (let i = 0; i < texts.length; i++) for (let j = i + 1; j < texts.length; j++) {
    const a = texts[i].b, c = texts[j].b;
    if (Math.min(a.right, c.right) - Math.max(a.left, c.left) > 2 && Math.min(a.bottom, c.bottom) - Math.max(a.top, c.top) > 2) clashes.push(`${texts[i].t} × ${texts[j].t}`);
  }
  const outside = texts.filter(x => x.plot && (x.b.left < box.left + labelW - 1 || x.b.right > box.left + W - padR + 1)).map(x => x.t);
  const card = svg.closest('[data-part="card"]').getBoundingClientRect();
  const vbW = +svg.getAttribute('viewBox').split(/\s+/)[2];
  const fits = vbW === W && box.left >= card.left - 0.5 && box.right <= card.right + 0.5;
  return { attr: W, css: box.width, fits, clashes, outside, scroll: document.documentElement.scrollWidth, inner: innerWidth };
};

