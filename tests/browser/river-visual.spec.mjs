test('river phase 2: laid out at its real width; labels never collide or leave the plot', async () => {
  for (const width of [960, 1280, 1600]) {
    const { context, page } = await open({ width });
    try {
      for (const zoom of ['term', 'year']) {
        if (zoom === 'year') { await page.locator('[data-part="zoom-pills"] [data-zoom="year"]').click(); await page.waitForTimeout(900); }
        const r = await page.evaluate(textAudit);
        assert.ok(Math.abs(r.attr - r.css) < 1, `at ${width}px the chart is scaled (${r.attr} drawn, ${r.css} shown)`);
        assert.ok(r.fits, `at ${width}px the chart's viewBox, width and card disagree`);
        assert.deepEqual(r.clashes, [], `labels collide at ${width}px (${zoom})`);
        assert.deepEqual(r.outside, [], `labels leave the plot at ${width}px (${zoom})`);
        assert.ok(r.scroll <= r.inner, `the page scrolls sideways at ${width}px`);
        if (zoom === 'term') {
          const weeks = await page.locator('[data-part="chart"] .tr-t-week').evaluateAll(n => n.filter(t => +(t.getAttribute('opacity') ?? 1) > 0 && /^((T\d|Hol) )?W\d+$|^H\d+$/.test(t.textContent)).length);
          assert.ok(weeks >= 5, `the Term zoom labels weeks, not months, at ${width}px (${weeks} week labels)`);
        }
        if (width === 960) await shot(page, `river-${zoom}-960`);
        if (width === 1280 && zoom === 'year') await shot(page, 'river-year-1280');
      }
    } finally { await context.close(); }
  }
});

test('river phase 2: agent badges and the Today pill never sit on a label', async () => {
  const { context, page } = await open({ width: 960 });
  try {
    for (const zoom of ['term', 'year']) {
    if (zoom === 'year') { await page.locator('[data-part="zoom-pills"] [data-zoom="year"]').click(); await page.waitForTimeout(900); }
    const hits = await page.evaluate(() => {
      const svg = document.querySelector('[data-part="chart"]');
      const texts = [...svg.querySelectorAll('text')].filter(t => t.textContent.trim() && !t.closest('.tr-agent')).map(t => ({ t: t.textContent, b: t.getBoundingClientRect() }));
      const out = [];
      const chips = [...svg.querySelectorAll('.tr-agent')].filter(c => +(c.getAttribute('opacity') ?? 1) > 0);
      const pill = svg.querySelector('[data-part="today"] rect').getBoundingClientRect();
      for (const x of texts) if (!x.t.includes('Today') && Math.min(pill.right, x.b.right) - Math.max(pill.left, x.b.left) > 1 && Math.min(pill.bottom, x.b.bottom) - Math.max(pill.top, x.b.top) > 1) out.push(`${x.t} under the Today pill`);
      for (let i = 0; i < chips.length; i++) for (let j = i + 1; j < chips.length; j++) {
        const a = chips[i].getBoundingClientRect(), b = chips[j].getBoundingClientRect();
        if (Math.min(a.right, b.right) - Math.max(a.left, b.left) > 1 && Math.min(a.bottom, b.bottom) - Math.max(a.top, b.top) > 1) out.push('two badges stacked');
      }
      for (const chip of chips) {
        const c = chip.getBoundingClientRect();
        for (const x of texts) if (Math.min(c.right, x.b.right) - Math.max(c.left, x.b.left) > 1 && Math.min(c.bottom, x.b.bottom) - Math.max(c.top, x.b.top) > 1) out.push(x.t);
      }
      return out;
    });
    assert.deepEqual(hits, [], zoom);
    }
  } finally { await context.close(); }
});

