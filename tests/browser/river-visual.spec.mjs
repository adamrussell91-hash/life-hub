test('river phase 3: Term ↔ Year is one continuous tween of the whole chart', async () => {
  const { context, page } = await open();
  try {
    const x0 = await barX(page, 'accreditation');
    await page.locator('[data-part="zoom-pills"] [data-zoom="year"]').click();
    const f = await frames(page, 800, () => ({ t: window.__termRiver.blend(), x: +document.querySelector('[data-part="term-river"] rect[data-id="accreditation"]').getAttribute('x') }));
    const ts = f.map(v => v.t);
    assert.ok(new Set(ts.map(t => t.toFixed(3))).size >= 10, 'the zoom passes through at least 10 in-between frames');
    assert.ok(ts.every((t, i) => !i || t >= ts[i - 1] - 0.02), 'the blend only moves toward Year (overshoot allowed ≤ 0.02)');
    assert.ok(Math.abs(ts.at(-1) - 1) < 0.001, 'it lands on Year');
    const x1 = f.at(-1).x;
    assert.ok(x1 > x0 + 100, 'Accreditation (from 07/09) slides right as the year opens out');
    const mid = f.find(v => v.t > 0.4 && v.t < 0.6);
    assert.ok(mid && mid.x > x0 && mid.x < x1, 'bars move with the blend, not snapping at the end');
    assert.equal(await page.locator('[data-part="zoom-pills"] [data-zoom="year"]').getAttribute('aria-pressed'), 'true');
    assert.match(await page.locator('[data-part="period"] b').textContent(), /Korea/);
    await page.keyboard.press('+');
    await page.waitForTimeout(800);
    assert.ok(Math.abs(await barX(page, 'accreditation') - x0) < 0.5, 'and back to Term exactly');
  } finally { await context.close(); }
});

test('river phase 3: reduced motion lands at once; resizing re-lays out without replaying', async () => {
  const { context, page } = await open({ reducedMotion: 'reduce', settle: 0 });
  try {
    await page.evaluate(() => new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r))));
    const full = await page.evaluate(() => { const { labelW, padR } = window.__termRiver.TR; return +document.querySelector('[data-part="chart"]').getAttribute('width') - labelW - padR; });
    assert.ok(Math.abs(await page.evaluate(clipW) - full) < 1, 'the plot is drawn immediately');
    await page.locator('[data-part="zoom-pills"] [data-zoom="year"]').click();
    await page.evaluate(() => new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r))));
    assert.equal(await page.evaluate(() => window.__termRiver.blend()), 1, 'the zoom lands at once');
  } finally { await context.close(); }
  const second = await open();
  try {
    const { page } = second;
    const w1 = await page.locator('[data-part="chart"]').evaluate(s => +s.getAttribute('width'));
    await page.setViewportSize({ width: 1100, height: 1100 });
    const ws = await frames(page, 700, clipW);
    const w2 = await page.locator('[data-part="chart"]').evaluate(s => +s.getAttribute('width'));
    assert.ok(w2 < w1, 'the chart re-lays out for the narrower column');
    const { labelW, padR } = await page.evaluate(() => window.__termRiver.TR);
    assert.ok(ws.slice(-5).every(w => Math.abs(w - (w2 - labelW - padR)) < 1) && ws.every(w => w > 100), 'resizing never replays the reveal');
  } finally { await second.context.close(); }
});

