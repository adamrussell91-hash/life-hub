// tests/unit/book-pack-import.test.js
// The book-pack importer and the copy check, on an invented pack (no book text). The real
// pack is private; tests/unit/get-things-done-copy.test.js checks against it where it exists.
import test from 'node:test';
import assert from 'node:assert/strict';
import { rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { copiedRun, shinglesOf, shippedStrings } from '../../scripts/book-pack/copy-check.mjs';
import { importSection } from '../../scripts/book-pack/import.mjs';

const steps = (prefix) => [
  { id: 'look', title: 'Look', prompt: `${prefix}: what is in front of you?` },
  { id: 'act', title: 'Act', prompt: `${prefix}: do the smallest useful thing.` }
];
const coaching = (when) => ({ when, failureModes: ['Doing it once.', 'Doing it for show.'], steps: steps(when.split(' ')[0]), exercise: 'Try it on one small thing this week.' });
const kept = (id, section, first, family, structure, extra = {}) => ({ id, title: id.slice(3), section, printedChapterPages: [first, first + 3], verdict: 'keep', mergeInto: null, tier: 'worksheet', reuse: null, family, structure, ...coaching(`Use ${id} when the kettle is cold.`), pairsWell: [], seeAlso: [], ...extra });

const PACK = {
  book: { prefix: 'zz', sections: [{ key: 'first' }, { key: 'second' }] },
  pages: ['Unrelated words fill this page.', 'Every morning the lighthouse keeper counts the gulls before the ferry leaves the harbour.'],
  entries: {
    zz_beta: kept('zz_beta', 'first', 20, 'path', { variant: 'stages', stages: [{ id: 'one', label: 'One' }, { id: 'two', label: 'Two' }] }),
    zz_alpha: kept('zz_alpha', 'first', 10, 'list', { layout: 'rows', groups: [{ id: 'near', label: 'Near' }, { id: 'far', label: 'Far' }], entry: 'Something seen' }, {
      facts: [{ claim: 'Gulls are counted.', page: 2, anchor: 'the lighthouse keeper counts the gulls before the ferry', check: 'matched' }],
      openQuestions: ['Secret question?'],
      structureEvidence: [{ figure: 'pdf-002-1', meaning: 'A figure.' }],
      pairsWell: ['zz_beta']
    }),
    zz_board: kept('zz_board', 'first', 30, 'list', {}, { reuse: { tool: 'kanban', fit: 'variant', differences: ['Book printed pp.28-31 (PDF pp.22-24) differs.'] } }),
    zz_rate: kept('zz_rate', 'first', 40, 'proposed', {}, { proposedFamily: { name: 'group_ratings', why: 'w', shape: 's' } }),
    zz_folded: { ...kept('zz_folded', 'first', 50, 'list', {}), verdict: 'merge', mergeInto: 'zz_alpha' },
    zz_gone: { ...kept('zz_gone', 'first', 60, 'list', {}), verdict: 'cut' },
    zz_elsewhere: kept('zz_elsewhere', 'second', 70, 'path', { variant: 'stages', stages: [{ id: 'a', label: 'A' }, { id: 'b', label: 'B' }] })
  }
};
const FAMILIES = '../families/index.mjs';

test('copy check: eight-word runs, case and apostrophes ignored', () => {
  const s = shinglesOf(['The quick brown fox jumps over the lazy dog’s bed today.']);
  assert.equal(copiedRun('so the Quick brown fox jumps over the lazy dogs', s), 'the quick brown fox jumps over the lazy');
  assert.equal(copiedRun('the quick brown fox jumps over a lazy dog', s), null);
  assert.equal(copiedRun('', s), null);
});

test('shippedStrings walks a definition, skipping functions and numbers', () => {
  assert.deepEqual(shippedStrings({ a: 'x', b: ['y', { c: 'z' }], f: () => 'no', n: 3 }).sort(), ['x', 'y', 'z']);
});

test('importer: the section’s kept entries in chapter order as factory calls', () => {
  const { source } = importSection(PACK, 'first', { familiesPath: FAMILIES });
  assert.match(source, /^\/\/ Generated by scripts\/book-pack\/import\.mjs/);
  assert.match(source, /import \{ listTool, pathTool \} from '\.\.\/families\/index\.mjs';/);
  assert.ok(source.indexOf("id: 'zz_alpha'") < source.indexOf("id: 'zz_beta'"));
  assert.match(source, /export const zzAlpha = listTool\(\{/);
  assert.match(source, /pairsWell: \['zz_beta'\]/);
  assert.match(source, /export const FIRST = Object\.freeze\(\{\n {2}zz_alpha: zzAlpha,\n {2}zz_beta: zzBeta\n\}\);/);
  assert.ok(!source.includes('zz_elsewhere'), 'other sections stay out');
});

test('importer: no facts, anchors, open questions, figures or PDF pages', () => {
  const { source } = importSection(PACK, 'first', { familiesPath: FAMILIES });
  for (const banned of ['lighthouse', 'facts', 'anchor', 'Secret', 'pdf-', 'PDF', 'pp.', 'printedChapterPages']) assert.ok(!source.includes(banned), banned);
});

test('importer: variants and proposed families become notes to finish by hand; merges and cuts are reported', () => {
  const { source, report } = importSection(PACK, 'first', { familiesPath: FAMILIES });
  assert.match(source, /\/\/ Variant of Problem Solver's `kanban`: finish by hand\.\nexport const zzBoardNotes = \{/);
  assert.match(source, /\/\/ Proposed family `group_ratings`: finish by hand\.\nexport const zzRateNotes = \{/);
  assert.match(source, /\/\/ Merged into zz_alpha: zz_folded \(fold in by hand\)\./);
  assert.deepEqual(report, { built: ['zz_alpha', 'zz_beta'], byHand: ['zz_board', 'zz_rate'], merged: [['zz_folded', 'zz_alpha']], cut: ['zz_gone'] });
});

test('importer: the generated module builds through the real factories', async () => {
  const pack = structuredClone(PACK);
  for (const e of Object.values(pack.entries)) e.id = e.id.replace(/^zz_/, 'gt_');
  pack.entries = Object.fromEntries(Object.values(pack.entries).map((e) => [e.id, e]));
  pack.entries.gt_alpha.pairsWell = ['gt_beta'];
  const { source } = importSection({ ...pack, book: { ...pack.book, prefix: 'gt' } }, 'first', { familiesPath: './index.mjs' });
  const file = fileURLToPath(new URL('../../packages/decision-book/families/__import-test.mjs', import.meta.url));
  writeFileSync(file, source);
  try {
    const mod = await import(`${file}?t=${Date.now()}`);
    assert.deepEqual(Object.keys(mod.FIRST), ['gt_alpha', 'gt_beta']);
    assert.equal(mod.FIRST.gt_alpha.family, 'list');
    assert.deepEqual(mod.FIRST.gt_beta.chart.stages.map((s) => s.id), ['one', 'two']);
    assert.equal(mod.FIRST.gt_alpha.steps[1].title, 'Act');
  } finally {
    rmSync(file);
  }
});

test('importer refuses to emit a run copied from the pack', () => {
  const copied = structuredClone(PACK);
  copied.entries.zz_alpha.when = 'Every morning the lighthouse keeper counts the gulls before breakfast.';
  assert.throws(() => importSection(copied, 'first', { familiesPath: FAMILIES }), /copied from the book: "every morning the lighthouse keeper counts the gulls…"/);
});

test('importer: an unknown section fails', () => {
  assert.throws(() => importSection(PACK, 'nope', { familiesPath: FAMILIES }), /no section nope/);
});
