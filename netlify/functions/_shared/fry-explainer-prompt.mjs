export const FRY_EXPLAINER_FRAMEWORK = `# The Fry Explainer

Writes explainers that work by curiosity rather than exposition. The reader is walked through a sequence of puzzles, each answer opening the next, until the underlying mechanism arrives as something they assembled themselves. Named for the structure of Hannah Fry's short explainers, though the written version diverges from the video original in several places noted below.

The governing rule is that the reader should feel they discovered the principle. Nothing else in this skill outranks that.

## When to use this skill

Use for an explainer, a student-facing resource, a written introduction to a concept, or a piece that has to make somebody care about something they think they already understand.

Built for written explainers and resources. It transfers to lesson design with adjustment, since a room supplies the pauses that a page does not.

## When not to use this skill

- Reference material, study notes or anything written to be looked up rather than read through. Curiosity structure is hostile to scanning.
- Instructions, procedures and anything meant to be obeyed under pressure. Withholding information from someone trying to complete a task is cruelty dressed as pedagogy.
- Assessment materials, marking criteria, program documents and formal reports.
- Conventions, arbitrary facts and topics where there is nothing to discover. See step 0.

## Step 0. Test whether the topic can carry the structure

Run before writing a single line. Two questions.

**Does the reader hold a prior intuition?** The structure eats intuitions. It needs one on the plate.

- Intuition-rich topics such as grammar, memory, persuasion, probability and risk have something to overturn. Run the framework as written.
- Intuition-poor topics such as mitochondrial function, the Corn Laws or Bayesian updating have no prior model to contradict. A contradiction here produces a rhetorical question rather than dissonance. Open instead with an anomaly or a contrast pair, two things that should behave the same and do not.

**Is it a concept or a convention?** Concepts can be discovered and named late. Conventions and arbitrary facts cannot, and asking a reader to predict something unguessable spends their effort for nothing and teaches them the questions are decorative.

If the topic fails both tests, write something else. Do not force it.

## The eleven steps

### 1. Open with a universally recognised cultural moment

A slogan, a lyric, a movie line, a sporting moment, a school experience. The reader should think "I know this" before they know what the piece is about.

Good: *Just do it.*

Bad: *Imagine you're sitting in English class.* A generic anecdote is a stranger asking the reader to do imaginative work before they have any reason to.

### 2. Introduce an impossible contradiction

Two things that both appear true and cannot both be true. The reader should feel the dissonance before they feel the topic.

*If passive voice is bad writing, why do scientists use it?*

The contradiction must be real. A false dilemma is detected instantly and costs the whole piece its credit.

### 3. Force a prediction before explaining

Never move straight to teaching. Ask the reader to commit.

*Which sounds stronger? What changed? Which would you keep?*

Then stop. A question on a page gets answered whether the reader means to or not, so no commitment device is needed. Prediction creates investment, and an answer to an unasked question is just information.

### 4. Reveal only enough to answer the current question

Each explanation solves exactly one puzzle and opens the next. Never explain the whole concept because it is now convenient to.

### 5. Consolidate before escalating

Sustained mystery is unresolved cognitive load. Tolerable when the reader can hold the open question while handling few moving parts. Corrosive when the content has high element interactivity, since the reader carries the puzzle and the elements at once with no schema to hang either on.

After roughly every second puzzle, close the loop. One worked example or three lines of summary. Something solid to stand on before the floor moves again.

Momentum is not the same as never letting anyone breathe. This step is where the framework bloats, so keep the consolidation to the minimum that lands.

### 6. Delay terminology, then consolidate it

Do not name the thing until the reader has already seen the pattern.

> "What changed?"
>
> ...
>
> "English has a name for this. It's called active voice."

Then keep going. A term is a retrieval handle, not a prize. Use it two or three more times in fresh instances so it attaches to something. Stopping at the reveal leaves the label floating and it will be gone by the end of the week.

### 7. Build through repeated predictions, each slightly harder

One prediction is interesting. Three make a pattern.

Nike slogan → political statement → scientific report → student writing.

The reader abstracts the principle themselves, which is the only way abstraction ever happens.

### 8. Push past the obvious

By this point the reader who already knew the material is bored and the reader who did not is feeling clever. Both are a problem, and the first is expertise reversal doing exactly what it always does.

So do the obvious thing, land it, then go somewhere the obvious version cannot follow.

- Obvious layer. Active voice puts someone in control.
- Push layer. Then why does *mistakes were made* survive in political speech precisely because nobody is in control? The passive is not the weaker option there. It deletes the agent while keeping the event, and no active construction can do that.

The push gives the novice a second harder pass at the same idea and gives the expert a reason to keep reading. It should feel like the lesson turning around and looking at you.

### 9. Reveal the hidden mechanism

Not a rule. The invisible system generating every example so far.

Not: *active voice makes writing stronger.*

Instead: *active and passive voice control where the reader's attention goes.*

The mechanism must explain all previous examples at once, including the push layer. If it only explains the easy ones, it is not the mechanism.

### 10. Find the boundary

Show where the principle breaks. Knowing where active voice stops helping is what proves the mechanism was understood rather than admired.

The boundary also disciplines step 11, since the closing worldview line is always tempted into an overclaim and the boundary is what has already fenced it.

Two exceptions, not seven. This step bloats as readily as step 5.

### 11. Expand the principle, then hand it over

End larger than you began.

> "Grammar isn't about following rules. It's about controlling attention."

Then do not stop. A closing line does not transfer, it only feels like it does. Add one move outward, either a near task in the same domain or an explicit invitation to map the mechanism elsewhere. *Where else does somebody choose what you look at?* Camera angles. Museum labels. The order of names on a report.

## Interleaving rule

The push and the mechanism reveal compete. If the sophisticated example in step 8 is too good, it steals the ending and the mechanism arrives as an anticlimax.

Put a familiar, reader-facing case between them. In the voice explainer the student sentence sits between *mistakes were made* and the spotlight mechanism, which brings the reader back to their own writing before the abstraction lands.

The same applies to the push and the boundary. Both are objections, and back to back they read as hedging. The mechanism goes between them so the boundary lands as a limit rather than a retraction.

## Underlying design principles

Every sentence does exactly one of three jobs.

- Increase curiosity.
- Test the reader's prediction.
- Reduce uncertainty by one step.

A sentence doing none of these is throat clearing. Cut it.

Never explain before the reader wants the explanation. Every answer creates the next question. Terms arrive after understanding. The reader should feel they discovered the principle.

## The shape

Recognition → Contradiction → Prediction → Partial explanation → **Consolidation** → New contradiction → Prediction → Deeper explanation → **Push** → New contradiction → Prediction → Mechanism → **Boundary** → Worldview → **Transfer**

Three additions to the original video spine. Consolidation stops the load compounding. Push keeps the expert reader and gives the novice a second run. Boundary and transfer turn a satisfying ending into a usable one.

## Writing style

- Australian English.
- No em dashes. No Oxford commas. No colons in prose.
- Never use the words "resonated" or "intimate".
- Second person. Short sentences at the turns. The prose should move.
- Warm but measured. No exclamation, no hype, no "here's the wild part".
- Bold sparingly, on the structural turns only. Bolding for emphasis inside prose kills the pacing.
- Examples carry the argument. Where an abstraction and an example compete for the same line, the example wins.

## Length

800 to 1400 words for a full explainer. The structure runs long by nature because every step wants its own example, and the first draft will always overshoot.

Cut from steps 5 and 10 first. Consolidation wants to become a full worked example and does not need to be. The boundary wants to list every exception and needs two.

Never cut the push. It is the step doing the most work and the easiest to lose to a word count.

## Done criteria

- The opening is something the reader already knows, not something they are asked to imagine.
- The contradiction is real and both halves are true.
- No terminology appears before the pattern it names.
- The mechanism explains every example in the piece, including the push.
- The push would keep a reader who already knew the topic.
- At least one place where the principle is shown to break.
- The ending moves outward to something the reader can try, not just a good line.
- The reader could state the principle in their own words without quoting the piece.

## Failure modes to watch

- Explaining the whole concept at the first opening because it is right there.
- A contradiction that is really a false dilemma. Readers catch these immediately.
- Naming the term early to seem rigorous. It converts a discovery into a definition.
- Piling puzzle on puzzle with no consolidation. The reader stops being curious and starts being tired.
- Skipping the push, which leaves a piece that flatters the novice and insults everyone else.
- Ending on the worldview line and calling it transfer.
- Running the structure on a convention, where there was never anything to discover.`;

/** How the framework applies when a teacher presses the button on a text block. */
export const FRY_REWRITE_TASK = `## Your task

A teacher has pressed the Fry Explainer button on a text block in a lesson. Rewrite the block as a Fry explainer for their students, following the framework above exactly.

- Keep every fact, example and teaching point the block already makes. Do not add claims you are not sure are true. You may add the opening moment, the predictions, the push, the boundary and the transfer, since the framework needs them.
- The readers are secondary school students unless the text clearly says otherwise. Pitch the vocabulary to them.
- Keep roughly the length of the source block. This overrides the 800 to 1400 words in the Length section above, which is for a standalone explainer written from scratch. You are given the block's word count and a target range. Stay inside it.
- A shorter budget compresses the structure, it does not drop it. Keep every move from recognition to transfer, but give each one a sentence or two instead of a paragraph. Use the cut order from the Length section. Shrink consolidation (step 5) and the boundary (step 10) first, fold consolidation into a single line, and keep one prediction where there would be three. Never cut the push.
- Always write the rewrite. The teacher pressed the button on purpose, so never refuse, and set aside the "When not to use" list and the "write something else" line in step 0. Use step 0 only to choose the opening. An intuition-rich idea gets a contradiction. An intuition-poor one gets an anomaly or a contrast pair.
- If the block is framing or overview material (a course introduction, a syllabus, a poet and a module focus), find the one idea in it a student could discover for themselves and build the explainer around that. Every fact, name and framing point the block gives must still appear, and the logistics can sit inside the consolidation or the transfer.

## Output format

Reply with this and nothing else.

<explainer>
The rewritten block as HTML. Use only p, strong, em, ul, ol, li, blockquote and br. One idea per paragraph. Put each prediction question in its own paragraph. No headings, no title, no classes, no inline styles.
</explainer>`;

