// "Since you last spoke" / "Talking points" LLM generation (Phase 3,
// Feature 3.2). This module owns three things:
//
//   1. `assembleSinceLastSpokeContext` — the only piece of I/O in this
//      module: fetches the person's `EntityOverview` (reusing
//      `assembleEntityOverview`, the same assembler Person Profile and
//      Feature 3.1's synchronous Brief sections already use — never
//      re-derives timeline logic) and their Observations, then hands both
//      to `person-brief-window.mjs`'s pure functions to compute the
//      "meaningful interaction" anchor and the structured "since then" facts.
//   2. `buildGenerationPrompt` / `generateBriefContent` — the prompt and the
//      Anthropic call, following the ONLY existing precedent for a direct
//      Anthropic call in this codebase, `knowledge-clementine-coach.mjs`
//      (`completeWithAnthropic`, the `env.ANTHROPIC_API_KEY` /
//      `deps.complete` injection pattern). Deliberately does NOT reuse that
//      file's `'claude-sonnet-4-6'` model id — see `MODEL_ID` below.
//   3. `buildOpeningLine` — the Brief's opening framing sentence ("You last
//      spoke 3 months ago, at the ... event. Since then:"), built
//      DETERMINISTICALLY from the exact `last_meaningful_interaction` facts
//      `assembleSinceLastSpokeContext` already has, never generated by the
//      LLM. An exact date and a real event/meeting/communication name are
//      facts already known precisely — better handled deterministically
//      than left to a model that could misstate them. The LLM is asked only
//      for the substantive "since then" bullets and "talking points",
//      exactly `collectChangesSince`'s structured `changes` object as input
//      — nothing more, per this feature's explicit "the LLM must never be
//      given license to look at anything else or invent facts not present
//      in the structured input" requirement.

// Current model id as of this session (see `docs/professional-hub` Feature
// 3.2 instructions and this repo's `claude-api` reference material).
// Deliberately NOT `'claude-sonnet-4-6'`, the id copied verbatim in
// `knowledge-clementine-coach.mjs` — that file's own header comment warns
// "check current model choice ... before copying verbatim, model IDs move."
const MODEL_ID = 'claude-sonnet-5';

const MAX_BULLETS = 4;
const MAX_BULLET_LENGTH = 400;

function cleanLabelFor(kind, ref, linkedRecords) {
  const bucket =
    kind === 'meeting' ? linkedRecords?.meetings
    : kind === 'event' ? linkedRecords?.events
    : kind === 'communication' ? linkedRecords?.communications
    : null;
  if (!bucket || !ref) return null;
  const match = bucket.find((item) => item.ref === ref);
  return match?.display_label ?? null;
}

/**
 * Fetches and assembles everything Feature 3.2 needs for one person:
 *  - `personDisplayName`: the subject's own display name (used only for the
 *    deterministic opening line, never sent to the LLM).
 *  - `lastMeaningfulInteraction`: `findLastMeaningfulInteraction`'s result,
 *    with `label` upgraded from the timeline's composed relationship-verb
 *    string (e.g. "attends Coffee meeting") to the real record's clean
 *    `display_label` (e.g. "Coffee meeting") via a lookup into the same
 *    `linked_records` bucket the synchronous Brief sections already use —
 *    falls back to the raw composed label if no match is found, rather than
 *    ever throwing.
 *  - `sinceIso`: `lastMeaningfulInteraction`'s date, or — the documented
 *    brand-new-person fallback — the person's own `created_at` when no
 *    meaningful interaction is recorded at all, so a brand-new person still
 *    gets a sensible, bounded prompt input rather than an unbounded
 *    "since forever" query.
 *  - `changes`: `collectChangesSince`'s structured object — this is the
 *    ENTIRE prompt input handed to the LLM (see `buildGenerationPrompt`).
 *  - `nowIso`: the exact "now" value used throughout, returned so the route
 *    can reuse the identical instant for `buildOpeningLine` rather than
 *    calling `now()` a second time and risking a (harmless but needless)
 *    skew between the two.
 */
export async function assembleSinceLastSpokeContext(personId, deps = {}) {
  const universalStore = deps.universalStore ?? (await (deps.getUniversalLinkStore ?? defaultGetUniversalLinkStore)());
  const professionalStore =
    deps.professionalStore ?? (await (deps.getProfessionalStore ?? defaultGetProfessionalStore)());
  const resolveEntity = deps.resolveEntity ?? defaultResolveEntity;
  const createRepository = deps.createRepository ?? createUniversalLinkRepository;
  const now = deps.now ?? (() => new Date().toISOString());

  const personRef = formatEntityRef({ namespace: 'shared', kind: 'person', id: personId });

  const overview = await assembleEntityOverview(personRef || personId, {
    store: universalStore,
    env: deps.env,
    fetchImpl: deps.fetchImpl,
    resolveEntity,
    createRepository
  });

  const observationRepo = createObservationRepository({ store: professionalStore });
  const observations = await observationRepo.listObservationsForAboutRef(overview.entity.ref);

  const relationshipLinks = [...overview.current_relationships, ...overview.historical_relationships];
  const nowIso = now();

  const rawLastInteraction = findLastMeaningfulInteraction(overview.timeline, observations, nowIso);
  // Documented fallback (brand-new person, nothing recorded at all): bound
  // "since" to the person's own `created_at` rather than querying an
  // unbounded "since forever" window.
  const sinceIso = rawLastInteraction?.date ?? overview.entity.created_at;

  const lastMeaningfulInteraction = rawLastInteraction
    ? {
        ...rawLastInteraction,
        label:
          rawLastInteraction.kind === 'observation'
            ? rawLastInteraction.label
            : cleanLabelFor(rawLastInteraction.kind, rawLastInteraction.ref, overview.linked_records) ??
              rawLastInteraction.label
      }
    : null;

  const changes = collectChangesSince(overview.timeline, observations, relationshipLinks, sinceIso, nowIso);

  return {
    personDisplayName: overview.entity.display_name,
    lastMeaningfulInteraction,
    sinceIso,
    changes,
    nowIso
  };
}

function describeRelativeTime(dateIso, nowIso) {
  const dateMs = Date.parse(dateIso);
  const nowMs = Date.parse(nowIso);
  if (Number.isNaN(dateMs) || Number.isNaN(nowMs)) return 'recently';
  const diffDays = Math.max(0, Math.round((nowMs - dateMs) / 86400000));
  if (diffDays === 0) return 'today';
  if (diffDays === 1) return 'yesterday';
  if (diffDays < 14) return `${diffDays} days ago`;
  if (diffDays < 60) return `${Math.round(diffDays / 7)} weeks ago`;
  if (diffDays < 365) return `${Math.round(diffDays / 30)} months ago`;
  return `${Math.round(diffDays / 365)} years ago`;
}

/**
 * The Brief's opening line, built deterministically from real structured
 * data — never left to the LLM (see module doc above for why). Phrased
 * honestly per the actual interaction kind rather than always claiming
 * "spoke": an email exchange or a logged Observation is not a conversation,
 * so only a `meeting`/`event` anchor uses "met"/"saw"; `communication` says
 * "exchanged a message"; `observation` says "noted something". Mirrors the
 * mockup's own opening line ("You last spoke 3 months ago, at the Gifted
 * Education Network event.") in spirit and structure, not verbatim wording,
 * since the mockup's single example is event-sourced and this Brief's real
 * data sources vary.
 */
export function buildOpeningLine(lastMeaningfulInteraction, now) {
  if (!lastMeaningfulInteraction) {
    return 'No prior interaction is recorded for this person yet. Since then:';
  }
  const { date, kind, label } = lastMeaningfulInteraction;
  const relative = describeRelativeTime(date, now);
  const cleanLabel = typeof label === 'string' ? label.trim() : '';

  switch (kind) {
    case 'meeting':
      return cleanLabel
        ? `You last met ${relative}, at "${cleanLabel}". Since then:`
        : `You last met ${relative}. Since then:`;
    case 'event':
      return cleanLabel
        ? `You last saw them ${relative}, at the ${cleanLabel}. Since then:`
        : `You last saw them ${relative}. Since then:`;
    case 'communication':
      return `You last exchanged a message ${relative}. Since then:`;
    case 'observation':
    default:
      return `You last noted something about them ${relative}. Since then:`;
  }
}

// The system prompt is real product work (brief section 19's "should feel
// like professional preparation, not surveillance" is a tone constraint,
// not plumbing) — written and organised as explicit, numbered rules rather
// than a one-line instruction, so each constraint is independently
// verifiable (including by this module's own tests, which assert on
// specific substrings rather than exact wording).
const SYSTEM_PROMPT = `You are drafting two short sections of a private "Person Brief" — a pre-meeting reading sheet someone prepares for themselves before reconnecting with a colleague or contact.

Tone: this must feel like professional preparation, not surveillance. Write the way a thoughtful colleague would jot a few notes before a catch-up — warm, plain, and squarely in service of the reader showing up well-informed and considerate. Never clinical, never invasive, and never phrased as though the person is being tracked, logged, or monitored. Avoid any language that reads like a case file, a dossier, or a surveillance report of someone's movements.

You will be given a single JSON object of structured facts about this person: what has changed since the reader last had a meaningful interaction with them (new observations, communications, meetings or events, and relationship changes such as a new role or a relationship ending), drawn directly from the reader's own records.

Rules you must follow exactly:
1. Use ONLY the facts given in the input. Never invent, infer, guess, or embellish any fact — a name, a date, an event, a role, an outcome, a feeling — that is not explicitly present in the structured input. If the input is sparse or empty, write less; do not pad with generic, speculative, or invented content to fill space.
2. Do not editorialise or speculate about the person's feelings, motives, or private life beyond what the input states.
3. Write in plain, warm, concise language — short bullet points, not full paragraphs. Each bullet should stand alone as one clear fact or talking point.
4. Respond with ONLY a single JSON object, no other text, no commentary, no markdown code fences, in exactly this shape:
   { "since_last_spoke": ["...", "..."], "talking_points": ["...", "..."] }
   - "since_last_spoke": up to 4 short bullet points summarising what has changed, drawn only from the structured input's facts. If there is genuinely nothing to report, return an empty array — never fabricate a bullet to avoid an empty list.
   - "talking_points": up to 4 short, natural conversation starters or things worth raising, grounded only in the given facts (for example, referencing a role change, a shared open item, or a recent event mentioned in the input) — never a generic icebreaker unconnected to the input. If the input gives you nothing to ground a talking point in, return an empty array.`;

/**
 * `structuredInput` here is exactly `collectChangesSince`'s return value —
 * the entire closed set of facts the model may draw on. Returns
 * `{ system, userMessage }`; `userMessage` JSON-serialises `structuredInput`
 * verbatim so nothing is paraphrased or summarised before the model sees it.
 */
export function buildGenerationPrompt(structuredInput) {
  const userMessage = [
    'Structured facts (the ENTIRE set of information you may use about this person — do not use any other knowledge):',
    '',
    JSON.stringify(structuredInput ?? {}, null, 2)
  ].join('\n');
  return { system: SYSTEM_PROMPT, userMessage };
}

async function completeWithAnthropic(system, messages, apiKey, fetchImpl) {
  const response = await fetchImpl('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'x-api-key': apiKey,
      'anthropic-version': '2023-06-01'
    },
    body: JSON.stringify({
      model: MODEL_ID,
      max_tokens: 1200,
      system,
      messages
    })
  });
  if (!response.ok) throw new Error(`Anthropic error ${response.status}`);
  const payload = await response.json();
  return payload.content?.find((block) => block.type === 'text')?.text ?? '';
}

function generationFailure(detail) {
  return Object.assign(new Error(`Brief generation failed: ${detail}`), {
    status: 502,
    code: 'brief_generation_failed',
    retryable: true
  });
}

// The model is instructed to return raw JSON, but strips a stray ```json
// fence defensively rather than failing a technically-recoverable response.
function extractJsonText(raw) {
  const trimmed = typeof raw === 'string' ? raw.trim() : '';
  const fenced = trimmed.match(/^```(?:json)?\s*([\s\S]*?)\s*```$/i);
  return fenced ? fenced[1] : trimmed;
}

// Validates and bounds a parsed bullet array server-side — never trusts the
// model's output shape or length blindly. Returns `null` (triggering a
// generation-failure response, not a silent pass-through) when the value
// isn't an array of strings at all; truncates rather than rejects when it's
// merely too long or a bullet is too long.
function sanitizeBullets(value) {
  if (!Array.isArray(value)) return null;
  const bullets = [];
  for (const item of value) {
    if (typeof item !== 'string') continue;
    const trimmed = item.trim();
    if (!trimmed) continue;
    bullets.push(trimmed.length > MAX_BULLET_LENGTH ? `${trimmed.slice(0, MAX_BULLET_LENGTH)}…` : trimmed);
    if (bullets.length >= MAX_BULLETS) break;
  }
  return bullets;
}

/**
 * Calls the model (or, in tests, `deps.complete`) and returns
 * `{ since_last_spoke, talking_points }` — both string arrays, capped at
 * `MAX_BULLETS`. Throws a `{ status: 502, code: 'brief_generation_failed',
 * retryable: true }` error (never returns garbage to the caller) when: the
 * completion call itself fails (network error, non-2xx), the response isn't
 * valid JSON, or the parsed JSON doesn't have the expected shape.
 */
export async function generateBriefContent({ structuredInput, apiKey, fetchImpl, complete }) {
  const { system, userMessage } = buildGenerationPrompt(structuredInput);
  const doComplete = complete ?? ((sys, messages) => completeWithAnthropic(sys, messages, apiKey, fetchImpl ?? fetch));

  let raw;
  try {
    raw = await doComplete(system, [{ role: 'user', content: userMessage }]);
  } catch (error) {
    throw generationFailure(error instanceof Error ? error.message : String(error));
  }

  let parsed;
  try {
    parsed = JSON.parse(extractJsonText(raw));
  } catch {
    throw generationFailure('model response was not valid JSON');
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw generationFailure('model response was not a JSON object');
  }

  const since_last_spoke = sanitizeBullets(parsed.since_last_spoke);
  const talking_points = sanitizeBullets(parsed.talking_points);
  if (!since_last_spoke || !talking_points) {
    throw generationFailure('model response did not match the expected { since_last_spoke, talking_points } shape');
  }

  return { since_last_spoke, talking_points };
}

